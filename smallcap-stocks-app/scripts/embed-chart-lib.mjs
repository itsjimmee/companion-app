#!/usr/bin/env node
import { readFileSync, writeFileSync, mkdirSync } from 'fs';
import { dirname, resolve } from 'path';
import { fileURLToPath } from 'url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const libPath = resolve(root, 'node_modules/lightweight-charts/dist/lightweight-charts.standalone.production.js');
const outDir = resolve(root, 'src/generated');
const outPath = resolve(outDir, 'lightweightChartsLib.ts');

const source = readFileSync(libPath, 'utf8');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  outPath,
  `/** Auto-generated by scripts/embed-chart-lib.mjs — do not edit */\nexport const LIGHTWEIGHT_CHARTS_LIB = ${JSON.stringify(source)};\n`,
  'utf8'
);
console.log(`Embedded lightweight-charts (${source.length} bytes) -> ${outPath}`);
